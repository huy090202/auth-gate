import { DEFAULT_THEME, convertCssVariables, defaultCssVariablesResolver, em, mergeMantineTheme, px } from '@mantine/core';
import { cssVariablesResolver, theme } from '../theme';

/*
 * Mantine would render the theme's CSS variables and its breakpoint helper classes as <style>
 * elements. The CSP forbids inline styles, so the provider runs with withCssVariables={false}
 * and withGlobalClasses={false} and this file generates the same rules once, into
 * the app's src/mantine-vars.css. A test in the app fails when the two drift; its gen:vars script
 * rewrites the file.
 */

type Vars = Record<string, string>;
type Resolved = { variables: Vars; light: Vars; dark: Vars };

export function mantineVarsCss(): string {
  const merged = mergeMantineTheme(DEFAULT_THEME, theme);
  const base = defaultCssVariablesResolver(merged) as Resolved;
  const own = cssVariablesResolver() as Resolved;
  const vars: Resolved = {
    variables: { ...base.variables, ...own.variables },
    light: { ...base.light, ...own.light },
    dark: { ...base.dark, ...own.dark },
  };
  const selector = ':root';
  const scheme = `
  ${selector}[data-mantine-color-scheme="dark"] { --mantine-color-scheme: dark; }
  ${selector}[data-mantine-color-scheme="light"] { --mantine-color-scheme: light; }
`;
  // The same rules as MantineClasses.
  const classes = (Object.keys(merged.breakpoints) as (keyof typeof merged.breakpoints)[]).reduce((acc, bp) => {
    const value: string = merged.breakpoints[bp] ?? '';
    const isPx = value.includes('px');
    const n = px(value) as number;
    const max = isPx ? `${n - 0.1}px` : em(n - 0.1);
    const min = isPx ? `${n}px` : em(n);
    return `${acc}@media (max-width: ${max}) {.mantine-visible-from-${bp} {display: none !important;}}@media (min-width: ${min}) {.mantine-hidden-from-${bp} {display: none !important;}}`;
  }, '');
  return `/* Generated by packages/web-kit/src/lib/mantine-vars.ts: run \`pnpm --filter console-web gen:vars\`. Do not edit. */\n${convertCssVariables(vars, selector)}${scheme}${classes}\n`;
}
